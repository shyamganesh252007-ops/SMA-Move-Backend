<?php
declare(strict_types=1);

/**
 * SMA-Move — Patient Invitation Data Model
 */

namespace SmaMove\Models;

require_once dirname(__DIR__) . '/config/database.php';

use SmaMove\Config\Database;
use PDO;

class PatientInvitation
{
    /**
     * Create a patient caregiver invitation.
     */
    public static function create(int $patientUserId, array $data): array
    {
        $pdo = Database::getConnection();

        // Custom code or auto-generate SMA-XXXX code
        $code = !empty($data['invitation_code'])
            ? strtoupper(trim($data['invitation_code']))
            : 'SMA-' . strtoupper(bin2hex(random_bytes(2)));

        $ttlDays = (int)($data['expires_in_days'] ?? 7);
        $expiresAt = date('Y-m-d H:i:s', time() + ($ttlDays * 86400));

        $sql = "INSERT INTO patient_invitations (
            patient_user_id,
            invitation_code,
            caregiver_name,
            caregiver_contact,
            relationship_type,
            can_view_care_plan,
            can_receive_summaries,
            can_edit_assistance,
            status,
            expires_at
        ) VALUES (
            :patient_user_id,
            :code,
            :name,
            :contact,
            :relation,
            :can_view,
            :can_sum,
            :can_edit,
            'active',
            :expires_at
        )";

        $stmt = $pdo->prepare($sql);
        $stmt->execute([
            ':patient_user_id' => $patientUserId,
            ':code' => $code,
            ':name' => $data['caregiver_name'] ?? null,
            ':contact' => $data['caregiver_contact'] ?? null,
            ':relation' => $data['relationship_type'] ?? 'Primary Family Member / Caregiver',
            ':can_view' => (int)($data['can_view_care_plan'] ?? 1),
            ':can_sum' => (int)($data['can_receive_summaries'] ?? 1),
            ':can_edit' => (int)($data['can_edit_assistance'] ?? 0),
            ':expires_at' => $expiresAt
        ]);

        $id = (int)$pdo->lastInsertId();

        return [
            'id' => $id,
            'patient_user_id' => $patientUserId,
            'invitation_code' => $code,
            'caregiver_name' => $data['caregiver_name'] ?? null,
            'caregiver_contact' => $data['caregiver_contact'] ?? null,
            'relationship_type' => $data['relationship_type'] ?? 'Primary Family Member / Caregiver',
            'can_view_care_plan' => (bool)($data['can_view_care_plan'] ?? true),
            'can_receive_summaries' => (bool)($data['can_receive_summaries'] ?? true),
            'can_edit_assistance' => (bool)($data['can_edit_assistance'] ?? false),
            'expires_at' => $expiresAt
        ];
    }

    /**
     * Find an active, unexpired invitation by code.
     */
    public static function findByCode(string $code): ?array
    {
        $pdo = Database::getConnection();

        $sql = "SELECT pi.*, u.full_name AS patient_name, u.email AS patient_email
                FROM patient_invitations pi
                JOIN users u ON pi.patient_user_id = u.id
                WHERE pi.invitation_code = :code
                  AND pi.status = 'active'
                  AND pi.expires_at > NOW()
                LIMIT 1";

        $stmt = $pdo->prepare($sql);
        $stmt->execute([':code' => strtoupper(trim($code))]);
        $row = $stmt->fetch(PDO::FETCH_ASSOC);

        return $row ?: null;
    }

    /**
     * Mark an invitation as accepted.
     */
    public static function markAccepted(int $id): bool
    {
        $pdo = Database::getConnection();
        $stmt = $pdo->prepare("UPDATE patient_invitations SET status = 'accepted' WHERE id = :id");
        return $stmt->execute([':id' => $id]);
    }

    /**
     * Get active invitations generated by a patient.
     */
    public static function getActiveInvitations(int $patientUserId): array
    {
        $pdo = Database::getConnection();
        $stmt = $pdo->prepare("SELECT * FROM patient_invitations WHERE patient_user_id = :puid AND status = 'active' AND expires_at > NOW() ORDER BY created_at DESC");
        $stmt->execute([':puid' => $patientUserId]);
        return $stmt->fetchAll(PDO::FETCH_ASSOC);
    }
}
